"""Builders for offline financial-statement and factor tests."""

from __future__ import annotations

from datetime import UTC, date, datetime

from equitytrace.models import FinancialFact, Issuer, Security
from equitytrace.repositories.ingestion import save_company_snapshot


def dt(year: int, month: int, day: int, hour: int = 21, minute: int = 0) -> datetime:
    return datetime(year, month, day, hour, minute, 0, tzinfo=UTC)


def make_fact(
    *,
    cik: str,
    concept: str,
    value: float,
    unit: str = "USD",
    start: date | None = None,
    end: date | None = None,
    available_at: datetime,
    accession: str,
    form: str,
    fiscal_year: int,
    fiscal_period: str,
    taxonomy: str = "us-gaap",
    frame: str | None = None,
) -> FinancialFact:
    return FinancialFact(
        cik=cik,
        taxonomy=taxonomy,
        concept=concept,
        unit=unit,
        value=value,
        start_date=start,
        end_date=end,
        filing_date=available_at.date(),
        acceptance_datetime=available_at,
        available_at=available_at,
        accession_number=accession,
        form=form,
        fiscal_year=fiscal_year,
        fiscal_period=fiscal_period,
        frame=frame,
    ).with_fact_id()


def seed_company(
    conn: object,
    *,
    ticker: str,
    cik: str,
    legal_name: str,
    facts: list[FinancialFact],
) -> None:
    save_company_snapshot(
        conn,  # type: ignore[arg-type]
        issuer=Issuer(cik=cik, legal_name=legal_name),
        securities=[Security(ticker=ticker, cik=cik, is_primary=True)],
        filings=[],
        facts=facts,
    )


